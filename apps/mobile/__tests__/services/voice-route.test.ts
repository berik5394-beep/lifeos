import { routeVoice } from '@/services/voice-route';

describe('один микрофон: кодовое слово и функции', () => {
  it.each([
    ['ЛайфОС, что у нас сегодня', 'что у нас сегодня'],
    ['лайфос что у нас сегодня?', 'что у нас сегодня?'],
    ['Привет, ЛайфОС! Какие планы?', 'Какие планы?'],
    ['лайф ос потратил 3000 на еду', 'потратил 3000 на еду'],
    ['Life OS, отметь тренировку', 'отметь тренировку'],
    ['что у нас сегодня', 'что у нас сегодня'],
  ])('«%s» → роботу «%s»', (input, text) => {
    expect(routeVoice(input)).toEqual({ kind: 'message', text });
  });

  it('слово, начинающееся на «лайфос…», не срезается как обращение', () => {
    expect(routeVoice('лайфосовский план')).toEqual({ kind: 'message', text: 'лайфосовский план' });
  });

  it('одно «ЛайфОС» без просьбы уходит как есть', () => {
    expect(routeVoice('ЛайфОС')).toEqual({ kind: 'message', text: 'ЛайфОС' });
  });

  it.each(['ЛайфОС, диктофон', 'лайфос включи диктофон', 'запиши встречу', 'записывай', 'Лайфос, запиши разговор'])(
    '«%s» → диктофон',
    (input) => {
      expect(routeVoice(input)).toEqual({ kind: 'dictation' });
    },
  );

  it('«запись к врачу завтра» — это не диктофон', () => {
    expect(routeVoice('запись к врачу завтра')).toEqual({ kind: 'message', text: 'запись к врачу завтра' });
    expect(routeVoice('включи запись')).toEqual({ kind: 'dictation' });
  });

  it('«запиши задачу купить хлеб» — это задача, не диктофон', () => {
    expect(routeVoice('запиши задачу купить хлеб')).toEqual({ kind: 'message', text: 'запиши задачу купить хлеб' });
  });

  it('режим разговора — только по кодовому слову', () => {
    expect(routeVoice('ЛайфОС, давай поговорим')).toEqual({ kind: 'conversation' });
    expect(routeVoice('давай поговорим про деньги')).toEqual({ kind: 'message', text: 'давай поговорим про деньги' });
  });
});
