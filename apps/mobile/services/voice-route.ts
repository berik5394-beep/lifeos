/**
 * Один микрофон на всё. Сказанное (или набранное) идёт роботу в единый мозг;
 * кодовое слово «ЛайфОС» в начале — просто обращение, его срезаем. Две функции,
 * у которых раньше были свои кнопки, включаются фразой:
 *  - диктофон: «ЛайфОС, диктофон», «запиши встречу», «записывай»;
 *  - режим разговора (без рук): «ЛайфОС, давай поговорим».
 */
export type VoiceRoute =
  | { kind: 'dictation' }
  | { kind: 'conversation' }
  | { kind: 'message'; text: string };

// «Привет, ЛайфОС», «эй лайф ос», «Life OS,» — распознавание пишет по-разному.
const WAKE = /^\s*(?:(?:привет|эй|хей|окей|ок|слушай)[\s,!.]+)?(?:лайф[\s-]?ос|лайфос|life[\s-]?os|lifeos)(?=$|[\s,.!?:;—-])[\s,.!?:;—-]*/i;

const DICTATION = /^(?:(?:включи|открой|запусти|начни)\s+)?диктофон(?=$|[\s,.!?])|^(?:включи|начни)\s+запись(?=$|[\s,.!?])|^запиши\s+(?:встречу|разговор|за\s+мной)|^записывай(?=$|[\s,.!?])/i;

const CONVERSATION = /^(?:давай\s+поговорим|поговори\s+со\s+мной|режим\s+разговора|включи\s+режим\s+разговора)(?=$|[\s,.!?])/i;

export function routeVoice(raw: string): VoiceRoute {
  const text = raw.trim();
  const wake = text.match(WAKE);
  const rest = wake ? text.slice(wake[0].length).trim() : text;
  if (DICTATION.test(rest)) return { kind: 'dictation' };
  // «Давай поговорим» без обращения — обычная фраза роботу; режим включаем только по кодовому слову.
  if (wake && CONVERSATION.test(rest)) return { kind: 'conversation' };
  // Одно «ЛайфОС» без просьбы — отдаём как есть: робот поздоровается.
  return { kind: 'message', text: rest || text };
}
