/** Что сказать на ответ: да/нет → текст; ответа нет → null. */
export function pitchAnswer(q: PitchQuestion, answer: 'yes' | 'no' | null): string | null {
  if (answer === 'yes') return q.yes;
  if (answer === 'no') return q.no;
  return null;
}
