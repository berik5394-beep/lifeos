import { describe, it, expect } from 'vitest';
import { isLifeMoment } from './life-moment.js';

/** Аудит 2026-11-10: жизненные моменты — к мозгу, не голой командой. */
describe('isLifeMoment', () => {
  it('чувство или важное событие без явной команды — к мозгу', () => {
    for (const t of [
      'Завтра у меня собеседование в Kaspi на аналитика, очень волнуюсь',
      'Мама ложится на операцию в пятницу',
      'Вчера поссорилась с братом из-за денег',
      'запиши собеседование на завтра, страшно',
      'Мы переезжаем в субботу',
    ]) expect(isLifeMoment(t), t).toBe(true);
  });
  it('деловые команды и обычные дела — быстрый путь', () => {
    for (const t of [
      'Поставь встречу собеседование в Kaspi завтра в 10',
      'Купить продукты завтра',
      'Встреча с поставщиком в понедельник в 11:30',
      'Создай задачу подготовить отчёт',
      'Радиатор починить в субботу',
    ]) expect(isLifeMoment(t), t).toBe(false);
  });
});
