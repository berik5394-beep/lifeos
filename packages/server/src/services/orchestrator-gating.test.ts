import { describe, it, expect } from 'vitest';
import {
  mayNeedLocalTools,
  mayNeedDealTools,
  isTelegramDataRequest,
  DEGRADED_ACTIONABLE_REFUSAL,
} from './jarvis-orchestrator.js';

/**
 * Fix D: localTools не должны включаться на болтовню (лишняя
 * стоимость/латентность + риск web_search+tools комбо). Регресс-тест
 * на эвристику включения.
 */

describe('mayNeedLocalTools', () => {
  it.each([
    'что у меня сегодня по задачам',
    'добавь задачу купить хлеб завтра',
    'сколько я потратил в этом месяце',
    'перенеси встречу на вечер',
    'разбери почту',
    'как я иду к годовой цели',
    'кто такой Серик',
    'дай телефон Айгерим',
    'что я говорил про брата',
    'помнишь про мою цель накопить',
    'какая сегодня погода',
    'что надеть на встречу',
    'во сколько выезжать в аэропорт',
  ])('«%s» → нужны инструменты', (t) => expect(mayNeedLocalTools(t)).toBe(true));

  it.each([
    'привет',
    'спасибо',
    'расскажи анекдот',
    'как дела',
    'ок',
  ])('«%s» → инструменты не нужны', (t) => expect(mayNeedLocalTools(t)).toBe(false));

  it('короткая реплика (<12 символов) всегда без инструментов', () => {
    expect(mayNeedLocalTools('задач?')).toBe(false);
  });
});

/** Словарь до сделок (16c0f5a) — при выключенных сделках включение инструментов байт-в-байт как раньше. */
const PRE_DEALS_TOOL_HINTS =
  /(задач|календар|встреч|событи|бюджет|потрат|расход|доход|привычк|напомн|почт|письм|gmail|расписан|план(?!ета)|поездк|цел[ьия]|сколько|что у меня|что сегодня|что по|добав|созда|отмет|перенес|свобод|кто так|телефон|контакт|номер|что я говорил про|помнишь про|погод|надеть|надену|одет|оденусь|выезж|вылет|лечу|бронь|билет|когда у меня|навык)/i;
const preDeals = (t: string): boolean => t.trim().length >= 12 && PRE_DEALS_TOOL_HINTS.test(t.trim());

/** Болтовня с «опасными» корнями сделок — инструменты не нужны ни при каком флаге (ревью-3 I5). */
const DEAL_CHITCHAT = [
  'а насчёт фильма что думаешь?',
  'за счёт чего растут мышцы?',
  'какой счёт в матче Реала?',
  'перевёл статью на английский',
  'он перевел дух и пошёл дальше',
  'придумай предложение со словом кот',
  'я согласился с ним, ты прав',
  'тысяча чертей, ну и день',
  'расскажи про тысячелетие',
  'скинул вес на 3 кг за месяц',
  'расчёт на завтрашнюю погоду не нужен',
];

describe('mayNeedLocalTools — словарь до сделок (ревью-3 I5: флаг off = как раньше)', () => {
  const corpus = [
    ...DEAL_CHITCHAT,
    'Ахмет хочет оборудование на 2 млн',
    'отправил Ахмету КП',
    'Ахмет оплатил',
    'Дана подписала договор',
    'Дана выставила счёт, ждём',
    'Ахмет перевёл 500 000',
    'как воронка по продажам?',
    'добавь задачу купить хлеб завтра',
    'сколько я потратил в этом месяце',
    'расскажи анекдот про кота',
    'привет, как ты?',
  ];
  it.each(corpus)('«%s» — как до сделок', (t) => expect(mayNeedLocalTools(t)).toBe(preDeals(t)));
});

describe('mayNeedDealTools — сделки (ревью B1/I-b, ревью-3 I5)', () => {
  it.each([
    'Ахмет хочет оборудование на 2 млн',
    'отправил Ахмету КП',
    'Ахмет оплатил',
    'Серик отказался, дорого',
    'перезвонить Ахмету во вторник',
    'новая сделка с Даной — склад',
    'Серик готов брать сервис, уже на переговорах',
    'как воронка?',
    'Дана подписала договор',
    'клиент Айгерим просит скидку',
    'Ахмет хочет оборудование на 500 тысяч',
    'Дана хочет склад за 800к',
    'отправил Ахмету предложение',
    'Ахмет подписал контракт',
    'Ахмет согласился на условия',
    'Ахмет перевёл 500 000',
    'Дана выставила счёт, ждём',
    'Ахмет передумал брать склад',
    'Дана хочет склад за 5 к',
    'Серик скинул 200 тысяч',
  ])('«%s» → инструменты сделок', (t) => expect(mayNeedDealTools(t)).toBe(true));
  it.each([...DEAL_CHITCHAT, 'кп', 'привет, как ты?', 'расскажи анекдот про кота', 'за 800к'])(
    'болтовня «%s» → без инструментов сделок',
    (t) => expect(mayNeedDealTools(t)).toBe(false),
  );
  it('«как там Ахмет по оборудованию?» — по словарю нет (ловит путь по имени клиента)', () => {
    expect(mayNeedLocalTools('как там Ахмет по оборудованию?')).toBe(false);
    expect(mayNeedDealTools('как там Ахмет по оборудованию?')).toBe(false);
  });
});

/**
 * ISSUE-1 — страховка перед 9A.8. Контракт: при падении tool-пути
 * сообщение, требующее инструментов, ДОЛЖНО получить честный отказ
 * (mayNeedLocalTools=true → отказ), а не деградированную выдумку.
 * Болтовня/инфо (false) деградирует нормально.
 */
describe('ISSUE-1 degraded-mode honest-refusal contract', () => {
  it('отказ явно говорит, что действие НЕ выполнено', () => {
    expect(DEGRADED_ACTIONABLE_REFUSAL).toMatch(/НЕ выполнен/i);
    expect(DEGRADED_ACTIONABLE_REFUSAL.length).toBeGreaterThan(20);
  });

  it.each([
    'добавь задачу купить хлеб завтра',
    'сколько я потратил в этом месяце',
    'разбери почту',
    'запиши расход 5000 на еду',
  ])('actionable «%s» → mayNeedLocalTools=true → при деградации отказ', (t) => {
    expect(mayNeedLocalTools(t)).toBe(true);
  });

  it.each(['расскажи анекдот', 'как дела', 'привет'])(
    'болтовня «%s» → false → деградирует нормально (web_search ок)',
    (t) => expect(mayNeedLocalTools(t)).toBe(false),
  );
});

