import { renderCrisisResources } from '../data/crisis-resources.js';

/**
 * Phase 6 C1 — ХАРДКОД safety-ответ. НЕ LLM, НЕ стиль, НЕ промпт.
 *
 * STYLE-AGNOSTIC BY CONSTRUCTION: функция не принимает и нигде не
 * читает assistantStyle. toxic/strict/любой стиль ФИЗИЧЕСКИ не
 * может сюда просочиться — это структурный инвариант (как
 * money-not-in-agent-loop), а не «правило в промпте». Поэтому
 * Safety всегда перебивает стиль: orchestrator при кризисе зовёт
 * это и делает ранний return ДО стиля/агента (wiring — 1e).
 *
 * Тон по VISION-WISE-FRIEND: валидация без диагноза, присутствие
 * без указаний, открытый вопрос, «не замена профессиональной
 * помощи». Коротко. Никаких «ты должен», никаких медицинских
 * выводов, без позиционирования себя терапевтом (но направить к
 * профессионалу — можно и нужно).
 */
/**
 * P1c (Berik deep-review): на ПОВТОРНЫЙ кризис-сигнал в той же
 * сессии empathy-рамка варьируется (иначе бот «читает скрипт» и
 * человек чувствует, что его не слышат). Ресурс-блок остаётся
 * ДЕТЕРМИНИРОВАННЫМ (112 + директивы всегда) — это надёжность.
 * arity 1 (с default) — .length === 0, style-agnostic инвариант
 * сохранён (default-параметры не считаются в arity).
 */
export function buildSafetyResponse(isRepeat = false): string {
  const empathy = isRepeat
    ? 'Я всё ещё рядом. Спасибо, что снова написал — это значит, ' +
      'ты ищешь, чтобы тебя услышали, и сам факт обращения уже шаг.'
    : 'Мне правда жаль, что тебе сейчас так тяжело. Спасибо, что ' +
      'написал об этом — это важно, и ты не один.';
  const closing = isRepeat
    ? 'Ты позвонил по номеру выше? Если ещё нет — это не упрёк. ' +
      'Расскажи, что происходит прямо сейчас, в эту минуту — я здесь.'
    : 'Я рядом и могу просто побыть с тобой в разговоре, если хочешь. ' +
      'А если захочешь — помогу найти специалиста, который поддержит ' +
      'профессионально. Как ты сейчас?';
  return [empathy, '', renderCrisisResources(), '', closing].join('\n');
}
