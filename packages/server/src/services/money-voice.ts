/**
 * Характер в денежном подтверждении (2026-11-10, тест «характер не поплыл»:
 * «Записать расход 15000 ₸? Подтверди — запишу» — одна и та же заготовка во
 * всех стилях, оценка 1–2). Подтверждение и сумма НЕ меняются (деньги — строго
 * через «да»), перед ним — одна фраза в стиле робота.
 *
 * Без модели: шаблоны, только из слов самого человека («копил на отпуск» →
 * цель «отпуск»). Ничего не выдумываем — ни чисел, ни лимитов.
 */
export type MoneyStyle = 'friendly' | 'strict' | 'calm' | 'toxic';

/** «хотя копил на отпуск», «зря», «не надо было» — человек сам жалеет о трате. */
const REGRET = /(?:^|[^а-яё])(?:хотя|зря|не\s+надо\s+было|не\s+стоило|сорвал[аи]?сь|импульс|опять|снова|копил[аи]?|откладывал[аи]?)(?![а-яё])/i;
const SAVING_FOR = /(?:копил[аи]?|коплю|откладывал[аи]?|откладываю)\s+на\s+([а-яё][а-яё\s-]{1,28}?)(?=[,.!?;]|$)/i;

export function savingGoalFrom(text: string): string | null {
  const m = text.match(SAVING_FOR);
  return m ? m[1].trim().replace(/\s+/g, ' ') : null;
}

const REGRET_LINES: Record<MoneyStyle, (goal: string | null) => string> = {
  friendly: (g) => (g ? `Бывает — хорошо, что честно говоришь. Цель «${g}» никуда не денется, наверстаем.` : 'Бывает — хорошо, что честно говоришь. Дальше будет легче.'),
  strict: (g) => (g ? `Копил на «${g}», а потратил мимо плана. Фиксируем — и завтра без лишних трат.` : 'Трата мимо плана. Фиксируем — и завтра без лишнего.'),
  calm: (g) => (g ? `Покупка уже сделана — без самоедства. Цель «${g}» остаётся, просто учтём это.` : 'Покупка уже сделана — без самоедства. Просто учтём и пойдём дальше.'),
  toxic: (g) => (g ? `Копил на «${g}», а купил это. Классика. Ладно, хоть запишем честно.` : 'Опять мимо плана. Ладно, хоть запишем честно.'),
};

const PLAIN_LINES: Record<MoneyStyle, string[]> = {
  friendly: ['Сейчас учтём — держу деньги в голове за тебя.', 'Понял, записываю, чтобы бюджет был перед глазами.'],
  strict: ['Правильно, что фиксируешь: учёт — это дисциплина.', 'Каждая трата — в учёт. Так и держим.'],
  calm: ['Хорошо, что отмечаешь — так видна вся картина.', 'Спокойно учтём — так деньги под присмотром.'],
  toxic: ['Ещё одна трата. Ну хоть не скрываешь.', 'Записываю, бухгалтер ты мой.'],
};

function styleOf(s: string | null | undefined): MoneyStyle {
  return s === 'strict' || s === 'calm' || s === 'toxic' ? s : 'friendly';
}

/** Одна фраза в стиле перед подтверждением расхода (детерминированно по сумме). */
export function expenseRemark(style: string | null | undefined, userText: string, amount: number): string {
  const st = styleOf(style);
  if (REGRET.test(userText)) return REGRET_LINES[st](savingGoalFrom(userText));
  const lines = PLAIN_LINES[st];
  return lines[Math.abs(Math.round(amount)) % lines.length];
}
