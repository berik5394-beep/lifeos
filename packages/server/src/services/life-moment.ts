/**
 * «Жизненный момент» (Berik 2026-11-10, аудит робота-друга): «Завтра собеседование,
 * очень волнуюсь» быстрый путь превращал в «Встреча создана» — волнение
 * игнорировалось; «Мама ложится на операцию» — в задачу. Такие фразы идут к
 * мозгу: он и запишет (встречей), и откликнется по-человечески.
 *
 * Чистая функция, без модели.
 */
/** Чувство в первом лице или о близком. */
const FEELING =
  /волну|переживаю|переживает|переживаем|боюсь|страшно|тревож|нервнича|тяжело|грустно|обидно|плохо мне|мне плохо|расстро|радуюсь|рад(?:а)?(?![а-яё])|счастлив|в шоке|паник|плачу|злюсь|бесит|не нахожу себе места|сердце не на месте/i;
/** Событие, после которого друг спросит «как ты?». */
const LIFE =
  /операци|больниц|реанимац|похорон|поминк|умер|умерл|скончал|диагноз|онколог|развод|расстал|поссор|ссор[аиуы]|беремен|роды|родил|свадьб|помолвк|уволил|уволили|сократили|собеседован|экзамен|защит[аыу] диплом|переезжа|переезд/i;
/** Явная команда («поставь встречу …», «создай задачу …») — быстрый путь ок, если нет чувства. */
const COMMAND = /(?:^|[^а-яё])(?:поставь|создай|добавь|запиши|запланируй|внеси|напомни|заведи)(?![а-яё])/i;

export function isLifeMoment(text: string): boolean {
  if (FEELING.test(text)) return true;
  return LIFE.test(text) && !COMMAND.test(text);
}
