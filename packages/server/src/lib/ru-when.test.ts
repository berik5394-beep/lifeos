import { describe, it, expect } from 'vitest';
import { parseRuWhen } from './ru-when.js';
import { deterministicIntent } from '../ai/intent-parser.js';

// Пн 2026-11-09
const T = '2026-11-09';

describe('parseRuWhen — «когда» из фразы задачи', () => {
  it.each([
    ['в пятницу позвонить маме в 15:00', '2026-11-13', '15:00', 'позвонить маме'],
    ['отчёт на 20 ноября', '2026-11-20', undefined, 'отчёт'],
    ['через 2 дня оплатить интернет', '2026-11-11', undefined, 'оплатить интернет'],
    ['через неделю к врачу', '2026-11-16', undefined, 'к врачу'],
    ['купить хлеб завтра', '2026-11-10', undefined, 'купить хлеб'],
    ['послезавтра забрать посылку', '2026-11-11', undefined, 'забрать посылку'],
    ['в понедельник планёрка', '2026-11-16', undefined, 'планёрка'],
    ['до среды сдать отчёт', '2026-11-11', undefined, 'сдать отчёт'],
    ['позвонить в 9 утра', T, '09:00', 'позвонить'],
    ['созвон в 7 вечера', T, '19:00', 'созвон'],
    ['оплатить садик 25.11', '2026-11-25', undefined, 'оплатить садик'],
    ['поздравить маму 5 января', '2027-01-05', undefined, 'поздравить маму'],
    ['купить молоко', T, undefined, 'купить молоко'],
  ])('«%s»', (text, date, time, rest) => {
    const r = parseRuWhen(text, T);
    expect(r).toEqual({ invalid: false, date, ...(time ? { time } : {}), rest });
  });

  it.each(['купить подарок на 31 ноября', 'встреча в 25:00', 'позвонить в банк вчера', 'в следующую пятницу отчёт'])(
    '«%s» — не решаем сами',
    (text) => {
      expect(parseRuWhen(text, T).invalid).toBe(true);
    },
  );
});

describe('быстрый путь create_task с датой и временем', () => {
  const now = new Date('2026-11-09T06:00:00Z'); // 11:00 Алматы, понедельник
  it('«напомни в пятницу позвонить маме в 15:00» → пятница 15:00', () => {
    expect(deterministicIntent('напомни в пятницу позвонить маме в 15:00', 'Asia/Almaty', now)).toMatchObject({
      action: 'create_task',
      title: 'позвонить маме',
      date: '2026-11-13',
      time: '15:00',
    });
  });
  it('«создай задачу купить подарок на 31 ноября» → не решаем (мозг переспросит)', () => {
    expect(deterministicIntent('создай задачу купить подарок на 31 ноября', 'Asia/Almaty', now)).toBeNull();
  });
});
