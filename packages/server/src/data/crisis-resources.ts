/**
 * Phase 6 C1 Safety — кризисные ресурсы (Казахстан, ru/kk).
 *
 * ИНВАРИАНТ ЧЕСТНОСТИ (класс bug #1, высшая ставка проекта):
 * НИКОГДА не отдаём пользователю в кризисе непроверенный номер.
 * Неверный номер «телефона доверия» = человек в кризисе звонит в
 * пустоту. Поэтому:
 *  - В коде статично ТОЛЬКО безусловно-верное: 112 (единая
 *    экстренная служба РК — стабильна) + директива к специалисту.
 *  - Конкретные «телефоны доверия» рендерятся ТОЛЬКО когда
 *    RESOURCES_VERIFIED === true И заполнен contact. Пока Берик не
 *    подтвердил официальные актуальные номера — флаг false, и
 *    рендер их структурно НЕ показывает (нельзя «забыть» —
 *    защита как money-not-in-agent-loop, не надежда на промпт).
 *  - Базовый ответ полностью функционален и корректен без них.
 */

export interface CrisisResource {
  name: string;
  /** Пусто, пока Берик не подтвердил официальный актуальный номер. */
  contact: string;
  note?: string;
  lang: 'ru' | 'kk';
}

/**
 * Берик переключает в true ТОЛЬКО после внесения подтверждённых
 * официальных номеров в HOTLINES (оба языка). До тех пор —
 * специфичные линии не показываются (structural-safe).
 */
export const RESOURCES_VERIFIED = false;

/** 112 единым источником живёт в BASELINE (без дублей в рендере). */

/**
 * Кандидаты «телефонов доверия» — contact ПУСТ намеренно. Берик
 * вносит официальные актуальные номера (источник: офиц. сайты
 * Минздрава РК / акиматов) и только тогда ставит RESOURCES_VERIFIED.
 * Я НЕ вписываю номера по памяти — устаревший/неверный crisis-номер
 * опаснее его отсутствия.
 */
export const HOTLINES: CrisisResource[] = [
  { name: 'Телефон доверия (психологическая помощь)', contact: '', lang: 'ru' },
  { name: 'Сенім телефоны (психологиялық көмек)', contact: '', lang: 'kk' },
];

/** ru/kk базовая директива — всегда корректна, без специфичных номеров. */
const BASELINE = {
  ru:
    'Если появляются мысли причинить себе вред — это серьёзно, и с этим ' +
    'не стоит оставаться в одиночку. Прямо сейчас можно позвонить 112 ' +
    '(экстренная служба, круглосуточно, бесплатно) или обратиться к ' +
    'врачу/психологу. LifeOS — не замена профессиональной помощи.',
  kk:
    'Қазір саған өте ауыр болса және өзіңе зиян келтіру ойлары пайда болса — ' +
    'өтінемін, бұнымен жалғыз қалма. Бұл маңызды. Қазір 112-ге ' +
    'қоңырау шалуға болады (тәулік бойы, тегін) немесе дәрігерге/' +
    'психологқа жүгін. Мен қасыңдамын, бірақ кәсіби көмектің орнын баса алмаймын.',
} as const;

/**
 * Текст ресурсов для safety-ответа. Всегда: baseline + 112.
 * Специфичные линии — ТОЛЬКО если verified И contact заполнен.
 */
export function renderCrisisResources(): string {
  const lines = [BASELINE.ru];
  if (RESOURCES_VERIFIED) {
    for (const h of HOTLINES) {
      if (h.contact.trim()) lines.push(`${h.name}: ${h.contact}`);
    }
  }
  return lines.join('\n');
}
