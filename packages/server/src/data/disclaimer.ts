import { renderCrisisResources } from './crisis-resources.js';

/**
 * Phase 6 C1 — SSOT дисклеймера (onboarding + settings).
 *
 * Юридический/культурный инвариант (VISION «мудрый друг, НЕ
 * психолог»): LifeOS НЕ позиционирует СЕБЯ терапевтом/психологом.
 * Направить к профессионалу — можно и нужно; назвать СЕБЯ им —
 * нельзя. Тест запрещает self-label «я психолог/терапевт».
 *
 * #4 SSOT: ресурсы (112/baseline) НЕ дублируются — берём из
 * renderCrisisResources() (единый источник, crisis-resources.ts).
 *
 * Две проекции одного текста:
 *  - SHORT — онбординг (показывается один раз: /auth/register +
 *    первое приветствие бота). Коротко, тёпло, без перегруза.
 *  - FULL — settings (всегда доступно): SHORT + ресурсы помощи.
 */

// Онбординг ≠ кризисный момент → SHORT только позиционирует.
// Конкретные номера (112/линии) — SSOT в crisis-resources, сюда
// НЕ копируются (#4); FULL подмешивает их через renderCrisisResources.
const SHORT =
  'LifeOS — твой AI-друг и помощник: помнит важное, помогает с ' +
  'планами, задачами и финансами, поддерживает в разговоре. Но он ' +
  'не врач и не замена профессиональной помощи. Если тебе тяжело ' +
  'или ты в кризисе — обратиться к специалисту это не слабость, а ' +
  'забота о себе.';

/** Онбординг: короткий дисклеймер (register + первый /start бота). */
export function disclaimerShort(): string {
  return SHORT;
}

/**
 * Settings: полный — короткий + ресурсы помощи (единый источник).
 * omitTailDisclaimer: SHORT уже содержит «не замена профессиональной
 * помощи» — повтор в ресурс-блоке убираем ПАРАМЕТРОМ рендера, не
 * копипастом/ручной обрезкой (#4 SSOT: фраза живёт в одном месте,
 * выключается по контексту).
 */
export function disclaimerFull(): string {
  return `${SHORT}\n\n${renderCrisisResources({ omitTailDisclaimer: true })}`;
}
