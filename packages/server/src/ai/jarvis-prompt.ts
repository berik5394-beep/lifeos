// --- ЧАСТЬ 3. КОНТЕКСТ (данные, пустые секции опускаются) ----------------
export function renderContext(ctx: AssistantContext): string {
  const done = ctx.todayTasks.filter((t) => t.completed).length;
  const pending = ctx.todayTasks.filter((t) => !t.completed);
  const genderLabel = ctx.assistantGender === 'male' ? 'мужской' : 'женский';
  const L: string[] = [
    'ДАННЫЕ ПОЛЬЗОВАТЕЛЯ',
    `Имя: ${ctx.userName}`,
    `Пол ассистента: ${genderLabel}`,
    `Время суток: ${getTimeOfDay()}`,
  ];
  if (ctx.todayTasks.length > 0) {
    L.push(`Задачи на сегодня: выполнено ${done} из ${ctx.todayTasks.length}`);
    if (pending.length > 0) {
      L.push(`Невыполненные: ${pending.map((t) => t.title).join(', ')}`);
    }
  }
  if (ctx.habitsProgress.total > 0) {
    L.push(
      `Привычки: ${ctx.habitsProgress.completed} из ${ctx.habitsProgress.total}`,
    );
  }
  if (ctx.pendingHabits && ctx.pendingHabits.length > 0) {
    L.push(
      `Сегодня НЕ отмечено: ${ctx.pendingHabits.join(', ')} — напомни, если к месту (йога/духовное/чтение тоже считаются).`,
    );
  }
  if (ctx.currentStreak > 0) L.push(`Серия: ${ctx.currentStreak} дней`);
  if (ctx.weeklyPlan) L.push(`План на неделю: ${ctx.weeklyPlan}`);
  if (ctx.upcomingEvents.length > 0) {
    L.push(
      `Ближайшие события: ${ctx.upcomingEvents
        .map((e) => `${e.title}${e.startTime ? ` в ${e.startTime}` : ''} (${e.date})`)
        .join('; ')}`,
    );
  }
  if (ctx.budgetLimit > 0) {
    const pct = Math.round((ctx.spentThisMonth / ctx.budgetLimit) * 100);
    L.push(
      `Финансы: потрачено за месяц ${ctx.spentThisMonth}₸ из ${ctx.budgetLimit}₸ (${pct}%)`,
    );
  } else if (ctx.spentThisMonth > 0) {
    L.push(`Финансы: потрачено за месяц ${ctx.spentThisMonth}₸ (бюджет не задан)`);
  }
  if (ctx.weekProgress > 0) {
    L.push(`Прогресс недели: ${Math.round(ctx.weekProgress * 100)}%`);
  }
  if (ctx.weatherToday) {
    L.push(
      `Погода сегодня: ${ctx.weatherToday} — учитывай при сборах/одежде/времени выезда на встречи.`,
    );
  }
  if (ctx.yearlyGoalsSummary && ctx.yearlyGoalsSummary !== 'Не заданы') {
    L.push(`Годовые цели: ${ctx.yearlyGoalsSummary}`);
  }
  if (ctx.memories && ctx.memories.length > 0) {
    L.push(
      '',
      'Что ты помнишь о пользователе:',
      ...ctx.memories.slice(0, 15).map((m) => `- ${m.content}`),
    );
  }
  return L.join('\n');
}

function ritualBlock(
  ritual: 'morning' | 'night',
  dayCompletionPercent?: number,
): string {
  if (ritual === 'morning') {
    return `\n\nРИТУАЛ УТРА: пользователь только открыл день. Коротко поприветствуй в своём стиле, дай настрой и обозначь главное на сегодня (из контекста). Не вываливай всё — 2-3 предложения, оставь место для его вопроса.`;
  }
  const pct =
    dayCompletionPercent != null ? ` Выполнение дня: ${Math.round(dayCompletionPercent)}%.` : '';
  return `\n\nРИТУАЛ НОЧИ: пользователь ложится спать.${pct} Подведи краткий итог дня по реальным данным в своём стиле и пожелай спокойной ночи. 2-4 предложения, мягко.`;
}

export interface JarvisPromptOpts {
  ritual?: 'morning' | 'night';
  dayCompletionPercent?: number;
  /** ISSUE-4: 'voice' → жёсткая краткость для TTS (≤3 предлож/~15с). */
  channel?: 'voice' | 'text';
  /** Phase 6 C3 — заменить STYLE-блок на THERAPEUTIC для эмо-хода.
   *  Активируется emotional-classifier из orchestrator. Therapeutic
   *  > toxic by construction (тон выше стиля для эмоций). Safety
   *  выше всего перебивает раньше — сюда уже НЕ-кризис. */
  therapeuticMode?: boolean;
  /** D (spec 2026-06-01): inline-проактивность из длинного рассказа.
   *  За флагом isV2InlineNudgeEnabled — off → поведение не меняется. */
  inlineNudge?: boolean;
  /** 2026-06 financial-goal-capture: записывать цель инструментом
   *  (suggest_goal спрашивает, пишет на «да»). За isV2SavingsCoachEnabled. */
  goalCapture?: boolean;
  /** Obligations: ловить обещания/долги из диалога → предложить
   *  create_obligation (запись на «да»). За isV2ObligationsEnabled. */
  obligationCapture?: boolean;
}

