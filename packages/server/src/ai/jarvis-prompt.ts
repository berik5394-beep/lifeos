export type AssistantStyle = 'friendly' | 'strict' | 'calm' | 'toxic';

export interface AssistantContext {
  userName: string;
  assistantStyle: AssistantStyle;
  assistantGender: string;
  todayTasks: { title: string; completed: boolean }[];
  habitsProgress: { total: number; completed: number };
  upcomingEvents: { title: string; startTime: string | null; date: string }[];
  spentThisMonth: number;
  budgetLimit: number;
  currentStreak: number;
  weekProgress: number;
  yearlyGoalsSummary: string;
  /** meta#9: имена активных привычек, НЕ отмеченных сегодня —
   *  чтобы мозг сам сказал «не отметил йогу/чтение», а не молчал. */
  pendingHabits?: string[];
  /** meta#9: план на эту неделю (WeeklyGoal): «N/M — тексты». */
  weeklyPlan?: string;
  /** Погода на сегодня — подмешивается только если есть событие
   *  сегодня (проактивно: «одевайся легко / выезжай раньше»). */
  weatherToday?: string;
  memories?: { type: string; content: string; importance: number }[];
  /** Phase 6 C5 — opt-out тёплого режима. false → orchestrator
   *  принудительно therapeuticMode=false в buildJarvisPrompt
   *  (даже если эмо-классификатор сработал). По умолчанию true. */
  therapeuticMode?: boolean;
}

export function getTimeOfDay(d = new Date()): 'утро' | 'день' | 'вечер' | 'ночь' {
  const h = d.getHours();
  if (h >= 5 && h < 12) return 'утро';
  if (h >= 12 && h < 17) return 'день';
  if (h >= 17 && h < 22) return 'вечер';
  return 'ночь';
}

