describe('detectMoneyIntent — как до сделок, кроме намеренных правок (ревью-3 N1–N3)', () => {
  it.each(SAME_AS_BEFORE)('«%s» — как до сделок', (t) => {
    expect(detectMoneyIntent(t)).toEqual(preDeals(t));
  });
  it.each(NOW_NOT_MONEY)('намеренно не деньги: «%s»', (t) => {
    expect(detectMoneyIntent(t)).toBeNull();
  });
  it.each(INTENDED)('намеренно: «%s»', (t, expected) => {
    expect(detectMoneyIntent(t)).toEqual(expected);
    // и это действительно отличие от прежнего (иначе — в SAME_AS_BEFORE)
    if (t !== 'потратил 3000тг на еду') expect(preDeals(t)).not.toEqual(expected);
  });
});
