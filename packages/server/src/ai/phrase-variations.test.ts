describe('вариации слов: фраза своими словами доходит до инструментов', () => {
  for (const c of CASES) {
    describe(c.tool, () => {
      it.each(c.phrases)('«%s»', (phrase) => {
        const fast = deterministicIntent(phrase);
        const action = fast?.action ?? null;
        if (action && action !== 'unknown') {
          // Быстрый путь сработал — только верным действием.
          expect(c.ok).toContain(action);
        } else {
          // Иначе — мозг с инструментами.
          expect(mayNeedLocalTools(phrase) || mayNeedDealTools(phrase)).toBe(true);
        }
      });
    });
  }
});

